import pytest
from src.masks import *

@pytest.fixture
def bad_types():
    return [None, [], {}, set(), object()]                       # типы данных которые вызывают ошибку TypeError

@pytest.mark.parametrize(
    "input_value, expected",
    [
        ("6831982476737658", "6831 98** **** 7658"),             # 16 цифр (строка)
        (6831982476737658, "6831 98** **** 7658"),               # 16 цифр (int)
        ("4111 1111 1111 1111", "4111 11** **** 1111"),          # с пробелами
        ("6831-9824-7673-7658", "6831 98** **** 7658"),          # с дефисами
        ("Visa 6831982476737658", "6831 98** **** 7658"),        # префикс текста
        ("1234567890", "1234 56** **** 7890"),                   # Минимальная допустимая длина (10)
        ("19273465960727348596", "1927 34** **** 8596"),         # Более 16 цифр — тот же формат, что и 16
        (1234.56789012, "1234 56** **** 9012"),                  # Вещественное число
        (-6831982476737658, "6831 98** **** 7658"),              # Отрицательное число
        ("Card#: 1234-56 78/9012;3456", "1234 56** **** 3456"),  # Различные символы вперемешку
        ("6831\u200b982476737658", "6831 98** **** 7658"),       # невидимый символ между цифрами
        ("9" * 100, "9999 99** **** 9999"),                      # максимально-допустимая длина
        ("１２３４５６７８９０１２", "１２３４ ５６** **** ９０１２"),   # unicode аналогично ASCII-цифрам
        # некорректные случаи
        ("123456789", "некорректный номер"),                     # 9 цифр
        ("", "некорректный номер"),                              # пустая строка
        ("abcdef", "некорректный номер"),                        # нет цифр
        ("5" * 110, "некорректный номер"),                       # очень длинный набор цифр
    ],
)
def test_get_mask_card_number(input_value, expected):
    assert get_mask_card_number(input_value) == expected

@pytest.mark.parametrize(
    "input_value, expected",
    [
        ("73654108430135874305", "**4305"),                      # 20 цифр (строка)
        (73654108430135874305, "**4305"),                        # 20 цифр (int)
        ("ACC 0000 1234 5678", "**5678"),                        # с пробелами
        ("6831-0000-1234-5678", "**5678"),                       # с дефисами
        ("Счет 6831982476737658", "**7658"),                     # префикс текста
        ("123456", "**3456"),                                    # Минимальная допустимая длина (6)
        (1234.56789012, "**9012"),                               # Вещественное число
        (-6831982476737658, "**7658"),                           # Отрицательное число
        ("Card#: 1234-56 78/9012;3456", "**3456"),               # Различные символы вперемешку
        ("6831\u200b982476737658", "**7658"),                    # невидимый символ между цифрами
        ("9" * 100, "**9999"),                                   # максимально-допустимая длина
        ("１２３４５６７８９０１２", "**９０１２"),                    # unicode аналогично ASCII-цифрам
        # некорректные случаи
        ("56789", "некорректный номер"),                         # 5 цифр
        ("", "некорректный номер"),                              # пустая строка
        ("abcdef", "некорректный номер"),                        # нет цифр
        ("5" * 110, "некорректный номер"),                       # очень длинный набор цифр
    ],
)
def test_get_mask_account(input_value, expected):
    assert get_mask_account(input_value) == expected

def test_get_mask_card_number_typeerror(bad_types):
    for bad in bad_types:
        with pytest.raises(TypeError):
            get_mask_card_number(bad)

def test_get_mask_account_typeerror(bad_types):
    for bad in bad_types:
        with pytest.raises(TypeError):
            get_mask_account(bad)